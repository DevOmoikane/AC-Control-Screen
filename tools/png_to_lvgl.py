#!/usr/bin/env python3
"""Convert a PNG into an LVGL image descriptor for the firmware.

The CYD panel is 320x240 with a 16 bit colour depth, so the splash artwork is
resized to the panel size and stored as RGB565, the same format the LVGL
display uses. The pixels end up in flash as a plain byte array, which means
the splash costs no RAM at runtime.

    tools/png_to_lvgl.py -i ac-control-cyberpunk/splash.png \\
                         -o src/splash/splash_img.c \\
                         --header src/splash/splash_img.h \\
                         --symbol splash_img

A splash is usually a logo on a black background. Storing the black border
around it would waste flash, so by default the image is cropped to the
brightest region and the offset of that region is written to the header. The
firmware draws the crop on a black rectangle at that offset, which looks the
same as the full image but takes a lot less space.

Use --threshold 0 to keep every pixel, or --no-crop to disable cropping.
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")


def parse_size(text):
    try:
        width, height = (int(part) for part in text.lower().split("x"))
    except ValueError:
        raise argparse.ArgumentTypeError("size must look like 320x240")
    if width <= 0 or height <= 0:
        raise argparse.ArgumentTypeError("size must be positive")
    return width, height


def luma(pixels):
    """Rec. 709 luminance of an (h, w, 3) uint8 array, as float."""
    return (
        0.2126 * pixels[:, :, 0]
        + 0.7152 * pixels[:, :, 1]
        + 0.0722 * pixels[:, :, 2]
    )


def crop_to_content(pixels, threshold):
    """Bounding box of the pixels brighter than threshold.

    Returns (x0, y0, x1, y1) inclusive, or None when nothing is bright
    enough and the whole image has to be kept.
    """
    brightness = luma(pixels)
    rows, cols = (brightness > threshold).nonzero()
    if rows.size == 0:
        return None
    return int(cols.min()), int(rows.min()), int(cols.max()), int(rows.max())


def to_rgb565(pixels):
    """RGB888 pixels -> RGB565 values, one per pixel, row major."""
    red = pixels[:, :, 0].astype(">u2") >> 3
    green = pixels[:, :, 1].astype(">u2") >> 2
    blue = pixels[:, :, 2].astype(">u2") >> 3
    return (red << 11) | (green << 5) | blue


def format_bytes(data, per_line=16):
    lines = []
    for start in range(0, len(data), per_line):
        chunk = data[start : start + per_line]
        lines.append("    " + " ".join(f"0x{byte:02x}," for byte in chunk))
    return "\n".join(lines)


def write_source(path, symbol, width, height, x, y, data):
    with open(path, "w") as handle:
        handle.write(
            f"""// Generated by tools/png_to_lvgl.py. Do not edit by hand.
//
// Source: splash.png, scaled to the panel size and cropped to the artwork.
// Stored as RGB565, little endian, which is what the LVGL display expects.

#include "{symbol}.h"

#if defined(__GNUC__)
__attribute__((aligned(4)))
#endif
const uint8_t {symbol}_data[{len(data)}] = {{
{format_bytes(data)}
}};

const lv_image_dsc_t {symbol} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = {width},
        .h = {height},
        .stride = {width * 2},
        .reserved_2 = 0,
    }},
    .data_size = sizeof({symbol}_data),
    .data = {symbol}_data,
    .reserved = NULL,
    .reserved_2 = NULL,
}};
"""
        )


def write_header(path, symbol, width, height, x, y):
    with open(path, "w") as handle:
        handle.write(
            f"""// Generated by tools/png_to_lvgl.py. Do not edit by hand.

// The guard is not the plain <SYMBOL>_H: that is the height constant
// below, and the two would fight over the same macro.
#ifndef {symbol.upper()}_H_INCLUDED
#define {symbol.upper()}_H_INCLUDED

#include <lvgl.h>

#ifdef __cplusplus
extern "C" {{
#endif

// Size of the cropped artwork, in pixels.
#define {symbol.upper()}_W {width}
#define {symbol.upper()}_H {height}
// Where the artwork sits on the 320x240 panel.
#define {symbol.upper()}_X {x}
#define {symbol.upper()}_Y {y}

extern const lv_image_dsc_t {symbol};

#ifdef __cplusplus
}}
#endif

#endif // {symbol.upper()}_H_INCLUDED
"""
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-i", "--input", required=True, help="source PNG")
    parser.add_argument("-o", "--output", required=True, help="generated C file")
    parser.add_argument("--header", help="generated header file")
    parser.add_argument("--symbol", default="image_dsc", help="name of the descriptor")
    parser.add_argument("--size", type=parse_size, default=(320, 240),
                        help="panel size, WxH (default 320x240)")
    parser.add_argument("--threshold", type=float, default=2.0,
                        help="luma above which a pixel counts as artwork (default 2)")
    parser.add_argument("--no-crop", action="store_true",
                        help="keep the whole image, do not crop to the artwork")
    args = parser.parse_args()

    width, height = args.size
    image = Image.open(args.input).convert("RGB")
    image = image.resize((width, height), Image.LANCZOS)

    import numpy as np

    pixels = np.asarray(image)
    box = None if args.no_crop else crop_to_content(pixels, args.threshold)
    if box is None:
        x0, y0, x1, y1 = 0, 0, width - 1, height - 1
    else:
        x0, y0, x1, y1 = box
    cropped = pixels[y0 : y1 + 1, x0 : x1 + 1]

    values = to_rgb565(cropped)
    # LVGL keeps RGB565 in host byte order and the display flush swaps it for
    # the panel, so the bytes are stored little endian.
    data = values.astype("<u2").tobytes()

    header = args.header or os.path.splitext(args.output)[0] + ".h"
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    os.makedirs(os.path.dirname(os.path.abspath(header)), exist_ok=True)

    cropped_width = x1 - x0 + 1
    cropped_height = y1 - y0 + 1
    write_source(args.output, args.symbol, cropped_width, cropped_height, x0, y0, data)
    write_header(header, args.symbol, cropped_width, cropped_height, x0, y0)

    print(f"{args.input}: {image.size[0]}x{image.size[1]} -> {cropped_width}x{cropped_height} at ({x0},{y0})")
    print(f"  {len(data)} bytes of RGB565 written to {args.output}")
    print(f"  header written to {header}")


if __name__ == "__main__":
    main()
